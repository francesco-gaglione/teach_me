#!/usr/bin/env python3
"""Generates GeneratedTokens.kt from docs/design/tokens.json (the source of truth).

Usage: python3 -I tools/generate_tokens.py
Run it whenever tokens.json changes. TokensMatchJsonTest fails if the generated file is stale.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT.parent / "docs/design/tokens.json"
OUT = ROOT / "core/designsystem/src/main/kotlin/com/teachme/core/designsystem/GeneratedTokens.kt"

EASING_NAMES = {"out": "easeOut", "inOut": "easeInOut", "in_": "easeIn", "linear": "linear"}


def num(v):
    return ("%g" % v)


def dp(v):
    return num(v) + ".dp"


def color(h):
    return "Color(0xFF%s)" % h[1:].upper()


def cap(s):
    return s[0].upper() + s[1:]


def main():
    t = json.loads(TOKENS.read_text())
    o = []
    w = o.append
    w("""package com.teachme.core.designsystem

import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.Shape
import androidx.compose.ui.graphics.toArgb
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

// GENERATED by tools/generate_tokens.py from docs/design/tokens.json (version %d). DO NOT EDIT BY HAND.
// Change tokens.json, run the script, and commit both. TokensMatchJsonTest fails if they diverge.
""" % t["version"])

    # Colors
    roles = list(t["color"]["light"])
    w("@Immutable\ndata class TeachColors(")
    for r in roles:
        w("    val %s: Color," % r)
    w(")\n")
    for mode in ("light", "dark"):
        w("internal val %sTeachColors = TeachColors(" % cap(mode))
        for r in roles:
            w("    %s = %s," % (r, color(t["color"][mode][r])))
        w(")\n")
    w("internal fun TeachColors.asMap(): Map<String, Int> = mapOf(")
    for r in roles:
        w('    "%s" to %s.toArgb(),' % (r, r))
    w(")\n")
    w("internal const val OVERLAY_OPACITY = %sf\n" % num(t["colorMeta"]["overlayOpacity"]))

    # dp groups
    def dp_group(name, key, cls_doc):
        vals = t[key]
        w("@Immutable\ndata class %s(" % name)
        for k, v in vals.items():
            w("    val %s: Dp = %s," % (k, dp(v)))
        w(")\n")
        w("internal fun %s.asMap(): Map<String, Float> = mapOf(" % name)
        for k in vals:
            w('    "%s" to %s.value,' % (k, k))
        w(")\n")

    dp_group("TeachSpacing", "spacing", "")
    dp_group("TeachLayout", "layout", "")
    dp_group("TeachStroke", "stroke", "")
    dp_group("TeachRadii", "shape", "")

    w("@Immutable\ndata class TeachShapes(")
    for k in t["shape"]:
        if k == "full":
            w("    val full: Shape = RoundedCornerShape(percent = 50),")
        elif k == "none":
            w("    val none: Shape = RoundedCornerShape(0.dp),")
        else:
            w("    val %s: Shape = RoundedCornerShape(%s),"
              % (k, dp(t["shape"][k])))
    w(")\n")

    # Elevation
    w("""/** Drop shadow spec: offset [y], [blur] radius and black alpha for each theme. */
@Immutable
data class TeachShadow(val y: Dp, val blur: Dp, val alphaLight: Float, val alphaDark: Float)

@Immutable
data class TeachElevation(""")
    for k, v in t["elevation"].items():
        al = v.get("alphaLight", v.get("alpha", 0))
        ad = v.get("alphaDark", v.get("alpha", 0))
        w("    val %s: TeachShadow = TeachShadow(%s, %s, %sf, %sf)," % (k, dp(v["y"]), dp(v["blur"]), num(al), num(ad)))
    w(")\n")

    # Motion
    m = t["motion"]
    w("""/** Duration and easing of one motion use case. */
@Immutable
data class MotionSpec(val durationMs: Int, val easing: CubicBezierEasing)

@Immutable
data class TeachMotion(""")
    for k, v in m["duration"].items():
        w("    val %sMs: Int = %d," % (k, v))
    for k, v in m["easing"].items():
        c = ", ".join(num(x) + "f" for x in v)
        w("    val %s: CubicBezierEasing = CubicBezierEasing(%s)," % (EASING_NAMES[k], c))
    for k, v in m["semantic"].items():
        w("    val %s: MotionSpec = MotionSpec(%d, CubicBezierEasing(%s))," % (
            k, v["duration"], ", ".join(num(x) + "f" for x in m["easing"][v["easing"]])))
    w(")\n")
    w("internal fun TeachMotion.durationsMap(): Map<String, Int> = mapOf(")
    for k in m["duration"]:
        w('    "%s" to %sMs,' % (k, k))
    for k in m["semantic"]:
        w('    "%s" to %s.durationMs,' % (k, k))
    w(")\n")


    # Highlighter (components/highlight.md): measures in dp, alphas as Float, times in ms.
    h = t["highlight"]
    w("/** Measures of the pen highlighter: `highlight` section of tokens.json (palette values are `palette*`). */")
    w('@Suppress("ktlint:standard:property-naming")\nobject TeachHighlight {')

    def h_entry(name, v):
        if name.endswith("Ms") or name == "tapMaxDuration":
            w("    val %s: Int = %d" % (name, v))
        elif "Alpha" in name:
            w("    val %s: Float = %sf" % (name, num(v)))
        else:
            w("    val %s: Dp = %s" % (name, dp(v)))

    for k, v in h.items():
        if k in ("note", "colors", "defaultColor", "syncRetryMs", "palette"):
            continue
        h_entry(k, v)
    for k, v in h["palette"].items():
        h_entry("palette" + cap(k), v)
    w("}\n")

    # Handwriting (components/handwriting.md): scalar measures only (lists and role names stay in the sources of the
    # enums). Dp for lengths, Int for times and counts, Float for alphas and the scale.
    hw = t["handwriting"]
    w("/** Measures of the handwriting layer: `handwriting` section of tokens.json (palette values are `palette*`). */")
    w('@Suppress("ktlint:standard:property-naming")\nobject TeachHandwriting {')
    float_keys = {"eraserGhostAlpha", "eraserRadius", "simplifyEpsilon"}
    int_keys = {"coordScale", "appSplitStrokeAtPoints", "undoDepth", "syncDebounceMs"}

    def hw_entry(name, v):
        if name in float_keys:
            w("    val %s: Float = %sf" % (name, num(v)))
        else:
            w("    val %s: Int = %d" % (name, v))

    for k in ("eraserGhostAlpha", "eraserRadius", "simplifyEpsilon", "coordScale", "appSplitStrokeAtPoints",
              "undoDepth", "syncDebounceMs"):
        hw_entry(k, hw[k])
    for k, v in hw["widths"].items():
        w("    val width%s: Dp = %s" % (cap(k), dp(v)))
    for k, v in hw["palette"].items():
        if k == "collapsedBelowWindowWidth":
            w("    val paletteCollapsedBelowWindowWidth: Dp = %s" % dp(v))
        else:
            w("    val palette%s: Dp = %s" % (cap(k), dp(v)))
    for k, v in hw["limits"].items():
        if isinstance(v, dict):
            w("    val limit%sMin: Int = %d" % (k.upper(), v["min"]))
            w("    val limit%sMax: Int = %d" % (k.upper(), v["max"]))
        else:
            w("    val limit%s: Int = %d" % (cap(k), v))
    w("}\n")

    # Typography
    fams = t["typography"]["fontFamilies"]
    w("""/** Font families resolved by the theme (see Typography.kt). */
@Immutable
data class TeachFonts(
    val ui: androidx.compose.ui.text.font.FontFamily,
    val reading: androidx.compose.ui.text.font.FontFamily,
    val code: androidx.compose.ui.text.font.FontFamily,
)
""")
    groups = {g: t["typography"][g] for g in ("ui", "reading", "code")}
    for g, styles in groups.items():
        w("@Immutable\ndata class Teach%sTypography(" % cap(g))
        for s in styles:
            w("    val %s: TextStyle," % s)
        w(")\n")
    w("@Immutable\ndata class TeachTypography(\n    val ui: TeachUiTypography,\n    val reading: TeachReadingTypography,\n"
      "    val code: TeachCodeTypography,\n)\n")
    w("internal fun teachTypography(fonts: TeachFonts): TeachTypography {")
    w("    fun style(family: androidx.compose.ui.text.font.FontFamily, weight: Int, size: Float, line: Float, "
      "spacing: Float, features: String? = null) =\n"
      "        TextStyle(\n            fontFamily = family,\n            fontWeight = FontWeight(weight),\n"
      "            fontSize = size.sp,\n            lineHeight = line.sp,\n            letterSpacing = spacing.sp,\n"
      "            fontFeatureSettings = features,\n        )")
    w("    return TeachTypography(")
    for g, styles in groups.items():
        w("        %s = Teach%sTypography(" % (g, cap(g)))
        for s, v in styles.items():
            feat = ', features = "liga 0, calt 0"' if g == "code" else ""
            w("            %s = style(fonts.%s, %d, %sf, %sf, %sf%s)," % (
                s, v["fontFamily"], v["fontWeight"], num(v["fontSize"]), num(v["lineHeight"]),
                num(v["letterSpacing"]), feat))
        w("        ),")
    w("    )\n}\n")
    w("internal fun TeachTypography.asMap(): Map<String, TextStyle> = mapOf(")
    for g, styles in groups.items():
        for s in styles:
            w('    "%s.%s" to %s.%s,' % (g, s, g, s))
    w(")")
    w("")
    w("internal val FontFamilyNames: Map<String, String> = mapOf(")
    for k, v in fams.items():
        w('    "%s" to "%s",' % (k, v["name"]))
    w(")")
    OUT.write_text("\n".join(o) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
