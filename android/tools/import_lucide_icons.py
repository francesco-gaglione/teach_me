#!/usr/bin/env python3
"""Imports Lucide icons (ISC license, https://lucide.dev) as stroke-only VectorDrawables.

Usage: python3 -I tools/import_lucide_icons.py
Source: lucide-static@LUCIDE_VERSION from jsDelivr. Stroke width follows tokens.json (layout.iconStroke).
Icons are tinted at runtime (colorFilter), so the stroke color here is plain black.
"""
import json
import pathlib
import urllib.request
import xml.etree.ElementTree as ET

LUCIDE_VERSION = "1.70.0"
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "core/designsystem/src/main/res/drawable"
TOKENS = ROOT.parent / "docs/design/tokens.json"
ICONS = [
    "circle-check", "circle-x", "circle-minus", "info", "lightbulb", "triangle-alert", "circle-alert",
    "lock", "key-round", "cloud-off", "loader", "chevron-right", "chevron-left", "x", "settings",
    "folder", "eye", "eye-off", "plus", "book-open", "link",
    "pencil", "trash-2", "ellipsis-vertical", "message-circle", "flag", "search", "circle-help",
    "send", "copy", "check", "arrow-down", "arrow-right", "wifi-off", "clock", "log-out", "rotate-ccw",
    "chevron-down", "history", "minus",
    "target", "circle-dot", "circle", "square-check-big", "text-cursor-input", "list-ordered", "layers",
    "pen-line", "list", "puzzle", "grip-vertical", "chevron-up", "book-marked", "external-link",
    "circle-arrow-right", "list-checks",
    "file-text", "file-up", "book", "newspaper", "flask-conical", "circle-play", "graduation-cap", "message-square",
    "users", "map-pin", "compass", "sparkles", "pause",
    "wallet",
    "image-off",
    "repeat",
    "eraser",
    "volume-2", "square",
    "highlighter", "undo-2", "redo-2",
]
NS = "{http://www.w3.org/2000/svg}"


def f(v):
    return ("%g" % float(v))


def circle_path(cx, cy, rx, ry):
    cx, cy, rx, ry = map(float, (cx, cy, rx, ry))
    return "M%g,%g a%g,%g 0 1,0 %g,0 a%g,%g 0 1,0 %g,0" % (cx - rx, cy, rx, ry, 2 * rx, rx, ry, -2 * rx)


def rect_path(a):
    x, y, w, h = (float(a.get(k, 0)) for k in ("x", "y", "width", "height"))
    rx = float(a.get("rx", a.get("ry", 0)))
    ry = float(a.get("ry", rx))
    if rx == 0 and ry == 0:
        return "M%g,%g h%g v%g h%g z" % (x, y, w, h, -w)
    return (
        "M%g,%g h%g a%g,%g 0 0 1 %g,%g v%g a%g,%g 0 0 1 %g,%g h%g a%g,%g 0 0 1 %g,%g v%g a%g,%g 0 0 1 %g,%g z"
        % (x + rx, y, w - 2 * rx, rx, ry, rx, ry, h - 2 * ry, rx, ry, -rx, ry, -(w - 2 * rx),
           rx, ry, -rx, -ry, -(h - 2 * ry), rx, ry, rx, -ry)
    )


def shape_to_path(el):
    tag = el.tag.replace(NS, "")
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        return circle_path(a["cx"], a["cy"], a["r"], a["r"])
    if tag == "ellipse":
        return circle_path(a["cx"], a["cy"], a["rx"], a["ry"])
    if tag == "line":
        return "M%s,%s L%s,%s" % (f(a["x1"]), f(a["y1"]), f(a["x2"]), f(a["y2"]))
    if tag in ("polyline", "polygon"):
        pts = a["points"].replace(",", " ").split()
        pairs = ["%s,%s" % (pts[i], pts[i + 1]) for i in range(0, len(pts), 2)]
        return "M" + " L".join(pairs) + (" z" if tag == "polygon" else "")
    if tag == "rect":
        return rect_path(a)
    raise ValueError("unsupported svg element: " + tag)


def main():
    stroke = json.loads(TOKENS.read_text())["layout"]["iconStroke"]
    OUT.mkdir(parents=True, exist_ok=True)
    for name in ICONS:
        url = "https://cdn.jsdelivr.net/npm/lucide-static@%s/icons/%s.svg" % (LUCIDE_VERSION, name)
        root = ET.fromstring(urllib.request.urlopen(url, timeout=30).read())
        paths = "\n".join(
            '    <path\n        android:pathData="%s"\n        android:strokeColor="#FF000000"\n'
            '        android:strokeWidth="%g"\n        android:strokeLineCap="round"\n'
            '        android:strokeLineJoin="round" />' % (shape_to_path(el), stroke)
            for el in root
        )
        xml = (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Lucide \"%s\" (lucide-static %s), ISC License, Copyright (c) Lucide Icons and Contributors.\n"
            "     Generated by tools/import_lucide_icons.py - do not edit by hand. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n'
            '    android:viewportHeight="24">\n%s\n</vector>\n' % (name, LUCIDE_VERSION, paths)
        )
        (OUT / ("ic_lucide_%s.xml" % name.replace("-", "_"))).write_text(xml)
    print("wrote", len(ICONS), "icons")


if __name__ == "__main__":
    main()
